// Writes the country table and the country names from scripts/countries.json.
//
//   node scripts/gen-countries.mjs
//     src/common/Countries.hxx: each country's code, atlas cell and catalog key,
//     and the atlas layout.
//     locales/*.po: country.XX in every catalog, as one block at the end of the
//     file that a later run replaces. The names come from ICU through
//     Intl.DisplayNames (Node's full ICU); a code with no name in any locale
//     stops the run before anything is written. Run scripts/subset-cjk-fonts.py
//     afterwards, since the Japanese, Korean and Chinese names need glyphs.
//
//   node scripts/gen-countries.mjs --pin <flag-icons folder> --sha256 <archive hash> --url <archive url> --release <tag>
//     Writes scripts/countries.json from a flag-icons release's country.json:
//     the ISO 3166-1 alpha-2 entries only, sorted by code. A pinned manifest is
//     reviewed and committed; the atlas (build-flag-atlas.mjs) reads it too.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = path.join(root, 'scripts', 'countries.json');
const args = process.argv.slice(2);
const option = (name) => { const at = args.indexOf(name); return at >= 0 ? args[at + 1] : undefined; };

function fail(message) { console.error(message); process.exit(1); }

if (args.includes('--pin')) {
    const folder = option('--pin'), sha256 = option('--sha256'), url = option('--url'), release = option('--release');
    if (!folder || !/^[0-9a-f]{64}$/.test(sha256 || '') || !url || !release) fail('--pin needs a folder, --sha256, --url and --release');
    const source = JSON.parse(fs.readFileSync(path.join(folder, 'country.json'), 'utf8'));
    const countries = source.filter((entry) => entry.iso === true && /^[a-z]{2}$/.test(entry.code))
        .map((entry) => ({ code: entry.code.toUpperCase(), name: entry.name }))
        .sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));
    if (new Set(countries.map((c) => c.code)).size !== countries.length) fail('country.json repeats a code');
    const manifest = {
        source: { project: 'lipis/flag-icons', release, archive: url, sha256, licence: 'MIT' },
        atlas: { cellWidth: 32, cellHeight: 24, padding: 2, columns: 16 },
        countries,
    };
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    console.log(`Pinned ${countries.length} countries to ${path.relative(root, manifestPath)}`);
    process.exit(0);
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const countries = manifest.countries;
countries.forEach((country, index) => {
    if (!/^[A-Z]{2}$/.test(country.code)) fail(`Not an alpha-2 code: ${country.code}`);
    if (index && countries[index - 1].code >= country.code) fail(`countries.json is not sorted by code at ${country.code}`);
});
const { cellWidth, cellHeight, padding, columns } = manifest.atlas;
const rows = Math.ceil(countries.length / columns);
const registry = JSON.parse(fs.readFileSync(path.join(root, 'locales', 'locales.json'), 'utf8'));
const tags = registry.locales.map((locale) => locale.tag);

// Every name first, so a gap stops the run with nothing half written.
const names = {};
const missing = [];
for (const tag of tags) {
    const display = new Intl.DisplayNames([tag], { type: 'region', fallback: 'none' });
    if (display.resolvedOptions().locale !== tag) fail(`ICU has no ${tag} region names (resolved ${display.resolvedOptions().locale})`);
    names[tag] = countries.map((country) => {
        const name = display.of(country.code);
        if (!name || name === country.code) missing.push(`${tag} ${country.code}`);
        return name;
    });
}
if (missing.length) fail(`No ICU name for:\n${missing.join('\n')}`);

const header = [
    '#pragma once',
    '// Generated by scripts/gen-countries.mjs from scripts/countries.json. Do not edit.',
    '// The ISO 3166-1 alpha-2 countries in code order. A row\'s index is its cell in',
    '// assets/flags/flags.png, and its key names it in locales/*.po.',
    'namespace sf4e { namespace countries {',
    'struct Row { char code[3]; int index; const char* key; };',
    `constexpr int Count = ${countries.length};`,
    'constexpr Row Table[Count] = {',
    ...countries.map((country, index) => `    {"${country.code}", ${index}, "country.${country.code}"},`),
    '};',
    '// The atlas: Columns cells across, each a CellWidth x CellHeight flag inside',
    '// Padding transparent pixels on every side, row after row in index order.',
    `constexpr int CellWidth = ${cellWidth}, CellHeight = ${cellHeight}, Padding = ${padding}, Columns = ${columns}, Rows = ${rows};`,
    'constexpr int SlotWidth = CellWidth + 2 * Padding, SlotHeight = CellHeight + 2 * Padding;',
    'constexpr int AtlasWidth = Columns * SlotWidth, AtlasHeight = Rows * SlotHeight;',
    '} }',
    '',
].join('\n');
fs.writeFileSync(path.join(root, 'src', 'common', 'Countries.hxx'), header);

const begin = '#. Country names, generated by scripts/gen-countries.mjs from ICU. Do not edit by hand.';
const end = '#. End of the generated country names.';
const quote = (text) => '"' + text.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
for (const tag of tags) {
    const file = path.join(root, 'locales', `${tag}.po`);
    let text = fs.readFileSync(file, 'utf8');
    // Written with the line endings the checkout gave the catalog.
    const eol = text.includes('\r\n') ? '\r\n' : '\n';
    const from = text.indexOf(begin);
    if (from >= 0) {
        const to = text.indexOf(end, from);
        if (to < 0) fail(`${tag}.po has the start of the country block but not its end`);
        text = text.slice(0, from) + text.slice(to + end.length);
    }
    text = text.replace(/\s*$/, eol + eol);
    const block = [begin, ''];
    countries.forEach((country, index) => block.push(`msgid "country.${country.code}"`, `msgstr ${quote(names[tag][index])}`, ''));
    block.push(end, '');
    fs.writeFileSync(file, text + block.join(eol));
}
console.log(`Wrote ${countries.length} countries to src/common/Countries.hxx and ${tags.length} catalogs`);
